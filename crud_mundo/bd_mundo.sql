create database bd_mundo;
use bd_mundo;

create table tb_governantes(
id_governante int primary key not null auto_increment,
nome varchar(100) not null,
partido varchar(100) not null,
dt_nascimento date not null,
idade int not null,
inicio_mandato date not null,
fim_mandato date
);

create table tb_continentes(
id_continente int primary key not null auto_increment,
nome varchar(100) not null,
populacao bigint not null,
area int not null,
qtd_paises int not null
);

create table tb_paises(
id_pais int primary key not null auto_increment,
id_continente int not null,
nome varchar(100) not null,
area int not null,
populacao bigint not null,
idioma varchar(30) not null,
id_governante int,
clima varchar(60) not null,
regime varchar(100) not null,
moeda varchar(60) not null,
foreign key (id_continente) references tb_continentes(id_continente),
foreign key (id_governante) references tb_governantes(id_governante)
);

create table tb_cidades(
id_cidade int primary key not null auto_increment,
nome varchar(100) not null,
id_pais int not null,
populacao int not null,
id_governante int,
clima varchar(60) not null,
dt_fundacao date not null,
foreign key (id_pais) references tb_paises(id_pais),
foreign key (id_governante) references tb_governantes(id_governante)
);

